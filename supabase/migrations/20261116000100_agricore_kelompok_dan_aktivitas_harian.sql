-- AgriCore: fondasi kelompok kerja dan aktivitas harian.
-- Additive migration: tidak mengubah atau menghapus tugas/laporan lama.

CREATE TABLE IF NOT EXISTS public.kelompok (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama text NOT NULL,
  deskripsi text,
  aktif boolean NOT NULL DEFAULT true,
  dibuat_oleh uuid NOT NULL DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT kelompok_nama_tidak_kosong CHECK (length(btrim(nama)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS kelompok_nama_aktif_unique
  ON public.kelompok (lower(btrim(nama))) WHERE aktif = true;

CREATE TABLE IF NOT EXISTS public.anggota_kelompok (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kelompok_id bigint NOT NULL REFERENCES public.kelompok(id) ON DELETE CASCADE,
  pegawai_id bigint NOT NULL REFERENCES public.pegawai(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (kelompok_id, pegawai_id)
);

CREATE INDEX IF NOT EXISTS anggota_kelompok_pegawai_idx
  ON public.anggota_kelompok (pegawai_id, kelompok_id);

CREATE TABLE IF NOT EXISTS public.tugas_kelompok (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kelompok_id bigint NOT NULL REFERENCES public.kelompok(id) ON DELETE RESTRICT,
  judul text NOT NULL,
  deskripsi text,
  jenis text NOT NULL DEFAULT 'Perawatan',
  lahan_id text,
  lahan_nama text,
  tanggal_mulai date NOT NULL DEFAULT current_date,
  tenggat date,
  target text,
  status text NOT NULL DEFAULT 'berjalan'
    CHECK (status IN ('berjalan','menunggu_verifikasi','selesai','dibatalkan')),
  dibuat_oleh uuid NOT NULL DEFAULT auth.uid(),
  diverifikasi_oleh uuid,
  diverifikasi_at timestamptz,
  catatan_verifikasi text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tugas_kelompok_judul_tidak_kosong CHECK (length(btrim(judul)) > 0),
  CONSTRAINT tugas_kelompok_tanggal_valid CHECK (tenggat IS NULL OR tenggat >= tanggal_mulai)
);

CREATE INDEX IF NOT EXISTS tugas_kelompok_group_status_idx
  ON public.tugas_kelompok (kelompok_id, status, tanggal_mulai DESC);

CREATE TABLE IF NOT EXISTS public.aktivitas_tugas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tugas_id bigint NOT NULL REFERENCES public.tugas_kelompok(id) ON DELETE RESTRICT,
  pegawai_id bigint NOT NULL REFERENCES public.pegawai(id) ON DELETE RESTRICT,
  tanggal date NOT NULL DEFAULT current_date,
  uraian text NOT NULL,
  hasil text,
  kendala text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT aktivitas_tugas_uraian_tidak_kosong CHECK (length(btrim(uraian)) > 0)
);

CREATE INDEX IF NOT EXISTS aktivitas_tugas_tugas_tanggal_idx
  ON public.aktivitas_tugas (tugas_id, tanggal DESC, created_at DESC);
CREATE INDEX IF NOT EXISTS aktivitas_tugas_pegawai_tanggal_idx
  ON public.aktivitas_tugas (pegawai_id, tanggal DESC);

ALTER TABLE public.kelompok ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.anggota_kelompok ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tugas_kelompok ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.aktivitas_tugas ENABLE ROW LEVEL SECURITY;

