-- Absensi harian pegawai SIMTANI
CREATE TABLE IF NOT EXISTS public.absensi (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pegawai_id bigint NOT NULL REFERENCES public.pegawai(id) ON DELETE CASCADE,
  auth_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  tanggal date NOT NULL DEFAULT CURRENT_DATE,
  masuk_at timestamptz,
  pulang_at timestamptz,
  masuk_lat double precision,
  masuk_lon double precision,
  masuk_alamat text,
  pulang_lat double precision,
  pulang_lon double precision,
  pulang_alamat text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT absensi_pegawai_tanggal_unique UNIQUE (pegawai_id, tanggal),
  CONSTRAINT absensi_lokasi_masuk_pair CHECK ((masuk_lat IS NULL) = (masuk_lon IS NULL)),
  CONSTRAINT absensi_lokasi_pulang_pair CHECK ((pulang_lat IS NULL) = (pulang_lon IS NULL))
);
ALTER TABLE public.absensi ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE ON public.absensi TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.absensi_id_seq TO authenticated;
DROP POLICY IF EXISTS absensi_select_own_or_admin ON public.absensi;
CREATE POLICY absensi_select_own_or_admin ON public.absensi FOR SELECT TO authenticated
USING (auth_user_id = auth.uid() OR EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'));
DROP POLICY IF EXISTS absensi_insert_own ON public.absensi;
CREATE POLICY absensi_insert_own ON public.absensi FOR INSERT TO authenticated
WITH CHECK (auth_user_id = auth.uid() AND EXISTS (SELECT 1 FROM public.pegawai pg WHERE pg.id = pegawai_id AND pg.auth_user_id = auth.uid()));
DROP POLICY IF EXISTS absensi_update_own_or_admin ON public.absensi;
CREATE POLICY absensi_update_own_or_admin ON public.absensi FOR UPDATE TO authenticated
USING (auth_user_id = auth.uid() OR EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'))
WITH CHECK (auth_user_id = auth.uid() OR EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'));
