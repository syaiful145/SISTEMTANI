-- AgriCore: keanggotaan pegawai pada lahan.
-- Additive only: tidak menghapus/mengubah kelompok, tugas, laporan, tanaman, atau absensi lama.

CREATE TABLE IF NOT EXISTS public.anggota_lahan (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lahan_id bigint NOT NULL REFERENCES public.lahan(id) ON DELETE RESTRICT,
  pegawai_id bigint NOT NULL REFERENCES public.pegawai(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','nonaktif')),
  tanggal_mulai date NOT NULL DEFAULT CURRENT_DATE,
  tanggal_selesai date,
  catatan text,
  dibuat_oleh uuid NOT NULL DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT anggota_lahan_tanggal_valid CHECK (tanggal_selesai IS NULL OR tanggal_selesai >= tanggal_mulai)
);

CREATE UNIQUE INDEX IF NOT EXISTS anggota_lahan_aktif_unique
  ON public.anggota_lahan (lahan_id, pegawai_id) WHERE status = 'aktif';
CREATE INDEX IF NOT EXISTS anggota_lahan_pegawai_status_idx
  ON public.anggota_lahan (pegawai_id, status, lahan_id);
CREATE INDEX IF NOT EXISTS anggota_lahan_lahan_status_idx
  ON public.anggota_lahan (lahan_id, status, pegawai_id);

ALTER TABLE public.anggota_lahan ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS anggota_lahan_admin_all ON public.anggota_lahan;
CREATE POLICY anggota_lahan_admin_all ON public.anggota_lahan
  FOR ALL TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid() AND lower(p.role) = 'admin'
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid() AND lower(p.role) = 'admin'
    )
  );

DROP POLICY IF EXISTS anggota_lahan_pegawai_select_own ON public.anggota_lahan;
CREATE POLICY anggota_lahan_pegawai_select_own ON public.anggota_lahan
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.pegawai pg
      WHERE pg.id = anggota_lahan.pegawai_id
        AND pg.auth_user_id = auth.uid()
        AND pg.status_verifikasi = 'disetujui'
    )
  );
