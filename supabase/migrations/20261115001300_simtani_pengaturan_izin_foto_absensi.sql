-- Pengaturan jam kerja, bukti foto absensi, dan pengajuan izin SIMTANI
ALTER TABLE public.absensi
  ADD COLUMN IF NOT EXISTS masuk_foto_path text,
  ADD COLUMN IF NOT EXISTS pulang_foto_path text,
  ADD COLUMN IF NOT EXISTS masuk_foto_captured_at timestamptz,
  ADD COLUMN IF NOT EXISTS pulang_foto_captured_at timestamptz,
  ADD COLUMN IF NOT EXISTS masuk_accuracy double precision,
  ADD COLUMN IF NOT EXISTS pulang_accuracy double precision;

CREATE TABLE IF NOT EXISTS public.pengaturan_absensi (
  id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  jam_masuk time NOT NULL DEFAULT '08:00',
  jam_pulang time NOT NULL DEFAULT '17:00',
  toleransi_terlambat integer NOT NULL DEFAULT 0 CHECK (toleransi_terlambat BETWEEN 0 AND 180),
  updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO public.pengaturan_absensi (id) VALUES (1) ON CONFLICT (id) DO NOTHING;
ALTER TABLE public.pengaturan_absensi ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE ON public.pengaturan_absensi TO authenticated;
DROP POLICY IF EXISTS pengaturan_absensi_select_auth ON public.pengaturan_absensi;
CREATE POLICY pengaturan_absensi_select_auth ON public.pengaturan_absensi
  FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS pengaturan_absensi_admin_write ON public.pengaturan_absensi;
CREATE POLICY pengaturan_absensi_admin_write ON public.pengaturan_absensi
  FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'));

CREATE TABLE IF NOT EXISTS public.izin_pegawai (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pegawai_id bigint NOT NULL REFERENCES public.pegawai(id) ON DELETE CASCADE,
  auth_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  tanggal_mulai date NOT NULL,
  tanggal_selesai date NOT NULL,
  jenis text NOT NULL CHECK (jenis IN ('Izin', 'Sakit')),
  alasan text NOT NULL,
  foto_path text NOT NULL,
  status text NOT NULL DEFAULT 'menunggu' CHECK (status IN ('menunggu', 'disetujui', 'ditolak')),
  catatan_admin text,
  diproses_oleh uuid REFERENCES auth.users(id),
  diproses_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (tanggal_selesai >= tanggal_mulai)
);
CREATE INDEX IF NOT EXISTS izin_pegawai_tanggal_idx ON public.izin_pegawai (tanggal_mulai, tanggal_selesai);
ALTER TABLE public.izin_pegawai ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE ON public.izin_pegawai TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.izin_pegawai_id_seq TO authenticated;
DROP POLICY IF EXISTS izin_select_own_or_admin ON public.izin_pegawai;
CREATE POLICY izin_select_own_or_admin ON public.izin_pegawai
  FOR SELECT TO authenticated
  USING (auth_user_id = auth.uid() OR EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'));
DROP POLICY IF EXISTS izin_insert_own ON public.izin_pegawai;
CREATE POLICY izin_insert_own ON public.izin_pegawai
  FOR INSERT TO authenticated
  WITH CHECK (
    auth_user_id = auth.uid()
    AND status = 'menunggu'
    AND EXISTS (SELECT 1 FROM public.pegawai pg WHERE pg.id = pegawai_id AND pg.auth_user_id = auth.uid())
  );
DROP POLICY IF EXISTS izin_admin_update ON public.izin_pegawai;
CREATE POLICY izin_admin_update ON public.izin_pegawai
  FOR UPDATE TO authenticated
  USING (EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'));
