-- AgriCore: fondasi penugasan dan draft laporan
-- Jalankan sekali di Supabase SQL Editor sebelum mengaktifkan menu penugasan.

create table if not exists public.tugas_pegawai (
  id bigint generated by default as identity primary key,
  judul text not null,
  jenis text not null check (jenis in ('Penanaman','Perawatan','Panen','Pemeriksaan tanaman')),
  deskripsi text,
  lahan_id text,
  lahan_nama text,
  pegawai_auth_id uuid not null,
  pegawai_nama text,
  tanggal_mulai date not null default current_date,
  tenggat date,
  status text not null default 'ditugaskan'
    check (status in ('ditugaskan','dikerjakan','selesai','dibatalkan')),
  dibuat_oleh uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists tugas_pegawai_auth_idx
  on public.tugas_pegawai (pegawai_auth_id, tanggal_mulai desc);
create index if not exists tugas_pegawai_status_idx
  on public.tugas_pegawai (status, tenggat);

create table if not exists public.draft_laporan (
  id uuid primary key default gen_random_uuid(),
  pegawai_auth_id uuid not null default auth.uid(),
  tugas_id bigint references public.tugas_pegawai(id) on delete set null,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists draft_laporan_owner_idx
  on public.draft_laporan (pegawai_auth_id, updated_at desc);

alter table public.tugas_pegawai enable row level security;
alter table public.draft_laporan enable row level security;

drop policy if exists "tugas_admin_all" on public.tugas_pegawai;
create policy "tugas_admin_all" on public.tugas_pegawai
  for all to authenticated
  using (
    exists (select 1 from public.profiles p
      where p.id = auth.uid() and p.role = 'admin')
  )
  with check (
    exists (select 1 from public.profiles p
      where p.id = auth.uid() and p.role = 'admin')
  );

drop policy if exists "tugas_pegawai_read_own" on public.tugas_pegawai;
create policy "tugas_pegawai_read_own" on public.tugas_pegawai
  for select to authenticated
  using (pegawai_auth_id = auth.uid());

drop policy if exists "tugas_pegawai_update_own_status" on public.tugas_pegawai;
create policy "tugas_pegawai_update_own_status" on public.tugas_pegawai
  for update to authenticated
  using (pegawai_auth_id = auth.uid())
  with check (pegawai_auth_id = auth.uid());

drop policy if exists "draft_pegawai_manage_own" on public.draft_laporan;
create policy "draft_pegawai_manage_own" on public.draft_laporan
  for all to authenticated
  using (pegawai_auth_id = auth.uid())
  with check (pegawai_auth_id = auth.uid());

drop policy if exists "draft_admin_read" on public.draft_laporan;
create policy "draft_admin_read" on public.draft_laporan
  for select to authenticated
  using (
    exists (select 1 from public.profiles p
      where p.id = auth.uid() and p.role = 'admin')
  );
