-- AgriCore: pekerjaan terjadwal per lahan dan penugasan fleksibel.
-- Tabel lama tugas_kelompok/aktivitas_tugas tidak dihapus atau diubah.

CREATE TABLE IF NOT EXISTS public.pekerjaan_lahan (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lahan_id bigint NOT NULL REFERENCES public.lahan(id) ON DELETE RESTRICT,
  judul text NOT NULL CHECK (length(btrim(judul)) > 0),
  instruksi text,
  jenis text NOT NULL DEFAULT 'Perawatan',
  tanggal date NOT NULL DEFAULT CURRENT_DATE,
  jam_mulai time,
  jam_selesai time,
  tenggat date,
  penerima_mode text NOT NULL DEFAULT 'semua' CHECK (penerima_mode IN ('semua','tertentu')),
  status text NOT NULL DEFAULT 'berjalan' CHECK (status IN ('berjalan','ditunda','selesai','dibatalkan')),
  dibuat_oleh uuid NOT NULL DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pekerjaan_lahan_jam_valid CHECK (jam_mulai IS NULL OR jam_selesai IS NULL OR jam_selesai > jam_mulai),
  CONSTRAINT pekerjaan_lahan_tanggal_valid CHECK (tenggat IS NULL OR tenggat >= tanggal)
);

CREATE INDEX IF NOT EXISTS pekerjaan_lahan_tanggal_status_idx
  ON public.pekerjaan_lahan (tanggal, status, lahan_id);

CREATE TABLE IF NOT EXISTS public.penugasan_lahan (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pekerjaan_id bigint NOT NULL REFERENCES public.pekerjaan_lahan(id) ON DELETE RESTRICT,
  pegawai_id bigint NOT NULL REFERENCES public.pegawai(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'berjalan'
    CHECK (status IN ('berjalan','menunggu_verifikasi','diterima','perlu_perbaikan','dibatalkan')),
  catatan_admin text,
  diverifikasi_oleh uuid,
  diverifikasi_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (pekerjaan_id, pegawai_id)
);

CREATE INDEX IF NOT EXISTS penugasan_lahan_pegawai_status_idx
  ON public.penugasan_lahan (pegawai_id, status, pekerjaan_id);

CREATE TABLE IF NOT EXISTS public.progres_lahan (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  penugasan_id bigint NOT NULL REFERENCES public.penugasan_lahan(id) ON DELETE RESTRICT,
  pegawai_id bigint NOT NULL REFERENCES public.pegawai(id) ON DELETE RESTRICT,
  tanggal date NOT NULL DEFAULT CURRENT_DATE,
  catatan text NOT NULL CHECK (length(btrim(catatan)) > 0),
  hasil text,
  kendala text,
  status text NOT NULL DEFAULT 'menunggu_verifikasi'
    CHECK (status IN ('menunggu_verifikasi','diterima','perlu_perbaikan')),
  catatan_admin text,
  diperiksa_oleh uuid,
  diperiksa_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (penugasan_id, tanggal)
);

CREATE INDEX IF NOT EXISTS progres_lahan_tanggal_status_idx
  ON public.progres_lahan (tanggal, status, penugasan_id);
CREATE INDEX IF NOT EXISTS progres_lahan_pegawai_tanggal_idx
  ON public.progres_lahan (pegawai_id, tanggal DESC);

ALTER TABLE public.pekerjaan_lahan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.penugasan_lahan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.progres_lahan ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS pekerjaan_lahan_admin_all ON public.pekerjaan_lahan;
CREATE POLICY pekerjaan_lahan_admin_all ON public.pekerjaan_lahan
  FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND lower(p.role)='admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND lower(p.role)='admin'));

DROP POLICY IF EXISTS pekerjaan_lahan_pegawai_select ON public.pekerjaan_lahan;
CREATE POLICY pekerjaan_lahan_pegawai_select ON public.pekerjaan_lahan
  FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.penugasan_lahan pl
    JOIN public.pegawai pg ON pg.id=pl.pegawai_id
    WHERE pl.pekerjaan_id=pekerjaan_lahan.id
      AND pg.auth_user_id=auth.uid() AND pg.status_verifikasi='disetujui'
  ));

DROP POLICY IF EXISTS penugasan_lahan_admin_all ON public.penugasan_lahan;
CREATE POLICY penugasan_lahan_admin_all ON public.penugasan_lahan
  FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND lower(p.role)='admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND lower(p.role)='admin'));

DROP POLICY IF EXISTS penugasan_lahan_pegawai_select_own ON public.penugasan_lahan;
CREATE POLICY penugasan_lahan_pegawai_select_own ON public.penugasan_lahan
  FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.pegawai pg
    WHERE pg.id=penugasan_lahan.pegawai_id
      AND pg.auth_user_id=auth.uid() AND pg.status_verifikasi='disetujui'
  ));

DROP POLICY IF EXISTS progres_lahan_admin_all ON public.progres_lahan;
CREATE POLICY progres_lahan_admin_all ON public.progres_lahan
  FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND lower(p.role)='admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND lower(p.role)='admin'));

DROP POLICY IF EXISTS progres_lahan_pegawai_select_own ON public.progres_lahan;
CREATE POLICY progres_lahan_pegawai_select_own ON public.progres_lahan
  FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.pegawai pg
    WHERE pg.id=progres_lahan.pegawai_id
      AND pg.auth_user_id=auth.uid() AND pg.status_verifikasi='disetujui'
  ));

DROP POLICY IF EXISTS progres_lahan_pegawai_insert_own ON public.progres_lahan;
CREATE POLICY progres_lahan_pegawai_insert_own ON public.progres_lahan
  FOR INSERT TO authenticated
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.pegawai pg
      WHERE pg.id=progres_lahan.pegawai_id
        AND pg.auth_user_id=auth.uid() AND pg.status_verifikasi='disetujui'
    )
    AND EXISTS (
      SELECT 1 FROM public.penugasan_lahan pl
      WHERE pl.id=progres_lahan.penugasan_id
        AND pl.pegawai_id=progres_lahan.pegawai_id
        AND pl.status IN ('berjalan','perlu_perbaikan')
    )
  );

DROP POLICY IF EXISTS progres_lahan_pegawai_update_own ON public.progres_lahan;
CREATE POLICY progres_lahan_pegawai_update_own ON public.progres_lahan
  FOR UPDATE TO authenticated
  USING (
    status='perlu_perbaikan'
    AND EXISTS (
      SELECT 1 FROM public.pegawai pg
      WHERE pg.id=progres_lahan.pegawai_id
        AND pg.auth_user_id=auth.uid() AND pg.status_verifikasi='disetujui'
    )
  )
  WITH CHECK (
    status='menunggu_verifikasi'
    AND EXISTS (
      SELECT 1 FROM public.pegawai pg
      WHERE pg.id=progres_lahan.pegawai_id
        AND pg.auth_user_id=auth.uid() AND pg.status_verifikasi='disetujui'
    )
    AND EXISTS (
      SELECT 1 FROM public.penugasan_lahan pl
      WHERE pl.id=progres_lahan.penugasan_id
        AND pl.pegawai_id=progres_lahan.pegawai_id
        AND pl.status='perlu_perbaikan'
    )
  );

CREATE OR REPLACE FUNCTION public.admin_buat_pekerjaan_lahan(
  p_lahan_id bigint,
  p_judul text,
  p_instruksi text,
  p_jenis text,
  p_tanggal date,
  p_jam_mulai time,
  p_jam_selesai time,
  p_tenggat date,
  p_penerima_mode text,
  p_pegawai_ids bigint[] DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  v_id bigint;
  v_count integer;
  v_mode text := coalesce(p_penerima_mode,'semua');
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND lower(p.role)='admin'
  ) THEN
    RAISE EXCEPTION 'Hanya Admin yang dapat membuat pekerjaan lahan.';
  END IF;
  IF p_judul IS NULL OR length(btrim(p_judul))=0 THEN
    RAISE EXCEPTION 'Judul pekerjaan wajib diisi.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.lahan l WHERE l.id=p_lahan_id AND l.aktif=true) THEN
    RAISE EXCEPTION 'Lahan tidak ditemukan atau tidak aktif.';
  END IF;
  IF v_mode NOT IN ('semua','tertentu') THEN
    RAISE EXCEPTION 'Pilihan penerima tidak valid.';
  END IF;
  IF v_mode='tertentu' AND coalesce(cardinality(p_pegawai_ids),0)=0 THEN
    RAISE EXCEPTION 'Pilih setidaknya satu pegawai.';
  END IF;
  IF v_mode='tertentu' AND EXISTS (
    SELECT 1 FROM unnest(p_pegawai_ids) x(id)
    WHERE NOT EXISTS (
      SELECT 1 FROM public.anggota_lahan al
      JOIN public.pegawai pg ON pg.id=al.pegawai_id
      WHERE al.lahan_id=p_lahan_id AND al.pegawai_id=x.id
        AND al.status='aktif' AND pg.status_verifikasi='disetujui'
    )
  ) THEN
    RAISE EXCEPTION 'Penerima harus anggota aktif dari lahan yang dipilih.';
  END IF;

  INSERT INTO public.pekerjaan_lahan
    (lahan_id,judul,instruksi,jenis,tanggal,jam_mulai,jam_selesai,tenggat,penerima_mode,dibuat_oleh)
  VALUES
    (p_lahan_id,btrim(p_judul),nullif(btrim(coalesce(p_instruksi,'')),''),coalesce(nullif(btrim(p_jenis),''),'Perawatan'),
     coalesce(p_tanggal,current_date),p_jam_mulai,p_jam_selesai,p_tenggat,v_mode,auth.uid())
  RETURNING id INTO v_id;

  IF v_mode='semua' THEN
    INSERT INTO public.penugasan_lahan (pekerjaan_id,pegawai_id)
    SELECT v_id,al.pegawai_id
    FROM public.anggota_lahan al
    JOIN public.pegawai pg ON pg.id=al.pegawai_id
    WHERE al.lahan_id=p_lahan_id AND al.status='aktif'
      AND pg.status_verifikasi='disetujui'
    ON CONFLICT (pekerjaan_id,pegawai_id) DO NOTHING;
  ELSE
    INSERT INTO public.penugasan_lahan (pekerjaan_id,pegawai_id)
    SELECT v_id,x.id FROM unnest(p_pegawai_ids) x(id)
    ON CONFLICT (pekerjaan_id,pegawai_id) DO NOTHING;
  END IF;

  GET DIAGNOSTICS v_count = ROW_COUNT;
  IF v_count=0 THEN
    RAISE EXCEPTION 'Tidak ada pegawai aktif yang terdaftar pada lahan ini.';
  END IF;
  RETURN jsonb_build_object('pekerjaan_id',v_id,'jumlah_penerima',v_count);
END;
$$;

REVOKE ALL ON FUNCTION public.admin_buat_pekerjaan_lahan(bigint,text,text,text,date,time,time,date,text,bigint[]) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_buat_pekerjaan_lahan(bigint,text,text,text,date,time,time,date,text,bigint[]) TO authenticated;

CREATE OR REPLACE FUNCTION public.pegawai_kirim_progres_lahan(
  p_penugasan_id bigint,
  p_tanggal date,
  p_catatan text,
  p_hasil text,
  p_kendala text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  v_pegawai_id bigint;
  v_id bigint;
  v_status text;
BEGIN
  SELECT pg.id INTO v_pegawai_id
  FROM public.pegawai pg
  WHERE pg.auth_user_id=auth.uid() AND pg.status_verifikasi='disetujui';
  IF v_pegawai_id IS NULL THEN RAISE EXCEPTION 'Akun pegawai tidak aktif.'; END IF;
  SELECT pl.status INTO v_status
  FROM public.penugasan_lahan pl
  WHERE pl.id=p_penugasan_id AND pl.pegawai_id=v_pegawai_id
  FOR UPDATE;
  IF NOT FOUND OR v_status NOT IN ('berjalan','perlu_perbaikan') THEN
    RAISE EXCEPTION 'Penugasan tidak aktif atau bukan milik Anda.';
  END IF;
  INSERT INTO public.progres_lahan
    (penugasan_id,pegawai_id,tanggal,catatan,hasil,kendala,status)
  VALUES
    (p_penugasan_id,v_pegawai_id,coalesce(p_tanggal,current_date),btrim(p_catatan),
     nullif(btrim(coalesce(p_hasil,'')),''),nullif(btrim(coalesce(p_kendala,'')),''),'menunggu_verifikasi')
  ON CONFLICT (penugasan_id,tanggal) DO UPDATE
    SET catatan=EXCLUDED.catatan,hasil=EXCLUDED.hasil,kendala=EXCLUDED.kendala,
        status='menunggu_verifikasi',catatan_admin=NULL,diperiksa_oleh=NULL,diperiksa_at=NULL,updated_at=now()
  RETURNING id INTO v_id;
  UPDATE public.penugasan_lahan SET status='menunggu_verifikasi' WHERE id=p_penugasan_id;
  RETURN v_id;
END;
$$;

REVOKE ALL ON FUNCTION public.pegawai_kirim_progres_lahan(bigint,date,text,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.pegawai_kirim_progres_lahan(bigint,date,text,text,text) TO authenticated;
